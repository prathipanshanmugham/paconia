// Builds prisma/migrations/<name>/migration.sql with Prisma's WebAssembly schema engine.
// Used where the Prisma engine binary cannot be downloaded. On the VPS, `prisma migrate deploy` applies it normally.
// Usage: node scripts/make-migration.mjs 0001_init   (needs: npm i --no-save @prisma/schema-engine-wasm@<matching>)
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { SchemaEngine } from '@prisma/schema-engine-wasm';
import { PrismaPg } from '@prisma/adapter-pg';
import { bindMigrationAwareSqlAdapterFactory } from '@prisma/driver-adapter-utils';

const name = process.argv[2] || '0001_init';
const content = readFileSync('prisma/schema.prisma', 'utf8');
const factory = new PrismaPg({ connectionString: process.env.DATABASE_URL || 'postgresql://x:x@localhost:5432/x' }, {});
// Wrap the factory the same way the Prisma CLI does before handing it to the wasm engine.
const adapter = bindMigrationAwareSqlAdapterFactory(factory);
const engine = await SchemaEngine.new({ datamodels: [['prisma/schema.prisma', content]] }, (m) => process.stderr.write(String(m) + '\n'), adapter);
const res = await engine.diff({
  from: { tag: 'empty' },
  to: { tag: 'schemaDatamodel', files: [{ path: 'prisma/schema.prisma', content }] },
  script: true, exitCode: null, filters: { externalTables: [], externalEnums: [] },
});
mkdirSync(`prisma/migrations/${name}`, { recursive: true });
writeFileSync(`prisma/migrations/${name}/migration.sql`, res.stdout);
writeFileSync('prisma/migrations/migration_lock.toml', '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
console.log(`wrote prisma/migrations/${name}/migration.sql (${res.stdout.length} chars)`);
